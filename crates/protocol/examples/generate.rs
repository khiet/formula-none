//! Write the web app's copy of the protocol: a TypeScript type per message
//! type through ts-rs, the protocol version, an index, and the sample
//! messages as bytes next to their JSON for Vitest (ADR 0004). Beside it,
//! the sim's types the bridge hands over as JavaScript values: the kart
//! readout, the surface under a kart, the standing and the tuning
//! (ADR 0026).
//!
//! `pnpm generate:protocol` runs this; CI runs it and fails on a diff
//! against the committed output. Each output directory is replaced whole,
//! so a type that no longer exists leaves no file behind.
//!
//! Usage: `cargo run -p protocol --example generate [-- <out-dir>]`; the
//! default is `apps/web/src/generated` in this repo, which gets a
//! `protocol` and a `sim` directory.

use protocol::{encode, samples, ClientMessage, ServerMessage, PROTOCOL_VERSION};
use serde::Serialize;
use sim::tuning::Tuning;
use sim::{KartReadout, Standing, Surface};
use std::error::Error;
use std::path::{Path, PathBuf};
use std::{env, fs};
use ts_rs::{Config, TS};

const DEFAULT_OUT_DIR: &str = "apps/web/src/generated";
const NOTE: &str = "// Generated by `pnpm generate:protocol` from crates/protocol. Do not edit.\n";

fn main() -> Result<(), Box<dyn Error>> {
    let out_dir = env::args()
        .nth(1)
        .map_or_else(default_out_dir, PathBuf::from);

    let protocol_dir = replaced(&out_dir.join("protocol"))?;
    let cfg = Config::new().with_out_dir(&protocol_dir);
    ClientMessage::export_all(&cfg)?;
    ServerMessage::export_all(&cfg)?;
    fs::write(
        protocol_dir.join("version.ts"),
        format!("{NOTE}export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"),
    )?;
    fs::write(protocol_dir.join("fixtures.json"), fixtures()?)?;
    fs::write(
        protocol_dir.join("index.ts"),
        index(
            &protocol_dir,
            Some("export { PROTOCOL_VERSION } from \"./version\";\n"),
        )?,
    )?;

    let sim_dir = replaced(&out_dir.join("sim"))?;
    let cfg = Config::new().with_out_dir(&sim_dir);
    KartReadout::export_all(&cfg)?;
    Standing::export_all(&cfg)?;
    Surface::export_all(&cfg)?;
    Tuning::export_all(&cfg)?;
    fs::write(sim_dir.join("index.ts"), index(&sim_dir, None)?)?;

    for dir in [protocol_dir, sim_dir] {
        println!("wrote {}", fs::canonicalize(&dir)?.display());
    }
    Ok(())
}

/// `dir`, emptied: made afresh whether or not it was there.
fn replaced(dir: &Path) -> Result<PathBuf, Box<dyn Error>> {
    if dir.exists() {
        fs::remove_dir_all(dir)?;
    }
    fs::create_dir_all(dir)?;
    Ok(dir.to_path_buf())
}

/// The repo's web app, found from this crate's manifest so the command runs
/// from any directory.
fn default_out_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(DEFAULT_OUT_DIR)
}

/// Re-export every generated type in `out_dir`, and then `extra`, from one
/// module.
fn index(out_dir: &Path, extra: Option<&str>) -> Result<String, Box<dyn Error>> {
    let mut names: Vec<String> = fs::read_dir(out_dir)?
        .filter_map(|entry| entry.ok())
        .filter_map(|entry| {
            let name = entry.file_name().to_string_lossy().into_owned();
            name.strip_suffix(".ts").map(str::to_owned)
        })
        .filter(|name| name != "index" && name != "version")
        .collect();
    names.sort();
    let mut index = NOTE.to_owned();
    for name in names {
        index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    index.push_str(extra.unwrap_or_default());
    Ok(index)
}

/// Every sample message as the bytes the Rust encoder produces and the JSON
/// of the same value, for Vitest to decode and encode through the bridge.
#[derive(Serialize)]
struct Fixtures {
    client: Vec<Fixture>,
    server: Vec<Fixture>,
}

/// Named as serde names the variant, which is how the Vitest side matches
/// a fixture to a member of the generated union.
#[derive(Serialize)]
struct Fixture {
    name: String,
    bytes: Vec<u8>,
    message: serde_json::Value,
}

fn fixtures() -> Result<String, Box<dyn Error>> {
    fn fixture<M: Serialize>(message: M) -> Fixture {
        let json = serde_json::to_value(&message).expect("messages are JSON-encodable");
        Fixture {
            name: variant_name(&json),
            bytes: encode(&message),
            message: json,
        }
    }
    let fixtures = Fixtures {
        client: samples::client().into_iter().map(fixture).collect(),
        server: samples::server().into_iter().map(fixture).collect(),
    };
    let mut json = serde_json::to_string_pretty(&fixtures)?;
    json.push('\n');
    Ok(json)
}

/// An externally tagged variant with fields is a one-key object and a unit
/// variant a string; either way the name is what serde wrote.
fn variant_name(message: &serde_json::Value) -> String {
    match message {
        serde_json::Value::String(name) => name.clone(),
        serde_json::Value::Object(fields) if fields.len() == 1 => {
            fields.keys().next().cloned().unwrap_or_default()
        }
        other => panic!("a message is a tagged variant, not {other}"),
    }
}
