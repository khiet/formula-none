// `pnpm generate:poster`: the poster kart from assets/karts/kart.glb, written
// for the web app to import and for docs/style-guide.html to load from disk.
// Both outputs are committed; CI regenerates them and fails on a difference.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseGlb } from "./glb.ts";
import { sideView } from "./side-view.ts";

const root = resolve(import.meta.dirname, "../../..");
const glb = resolve(root, "assets/karts/kart.glb");
const view = sideView(parseGlb(new Uint8Array(readFileSync(glb))));
const json = JSON.stringify(view, null, 2);
const header = "Generated by `pnpm generate:poster` from assets/karts/kart.glb; do not edit.";

writeFileSync(resolve(root, "apps/web/src/generated/kart/side.json"), `${json}\n`);
writeFileSync(resolve(root, "docs/kart-side.js"), `// ${header}\nconst KART_SIDE = ${json};\n`);
console.log(`poster kart: ${view.paths.length} paths from ${glb}`);
