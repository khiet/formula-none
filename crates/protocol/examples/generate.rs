//! Write the web app's copy of the protocol: a TypeScript type per message
//! type through ts-rs, the protocol version, an index, and the sample
//! messages as bytes next to their JSON for Vitest (ADR 0004).
//!
//! `pnpm generate:protocol` runs this; CI runs it and fails on a diff
//! against the committed output. The output directory is replaced whole, so
//! a type that no longer exists leaves no file behind.
//!
//! Usage: `cargo run -p protocol --example generate [-- <out-dir>]`; the
//! default is `apps/web/src/generated/protocol` in this repo.

use protocol::{encode, samples, ClientMessage, ServerMessage, PROTOCOL_VERSION};
use serde::Serialize;
use std::error::Error;
use std::path::{Path, PathBuf};
use std::{env, fs};
use ts_rs::{Config, TS};

const DEFAULT_OUT_DIR: &str = "apps/web/src/generated/protocol";
const NOTE: &str = "// Generated by `pnpm generate:protocol` from crates/protocol. Do not edit.\n";

fn main() -> Result<(), Box<dyn Error>> {
    let out_dir = env::args()
        .nth(1)
        .map_or_else(default_out_dir, PathBuf::from);
    if out_dir.exists() {
        fs::remove_dir_all(&out_dir)?;
    }
    fs::create_dir_all(&out_dir)?;

    let cfg = Config::new().with_out_dir(&out_dir);
    ClientMessage::export_all(&cfg)?;
    ServerMessage::export_all(&cfg)?;

    fs::write(
        out_dir.join("version.ts"),
        format!("{NOTE}export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"),
    )?;
    fs::write(out_dir.join("fixtures.json"), fixtures()?)?;
    fs::write(out_dir.join("index.ts"), index(&out_dir)?)?;

    println!("wrote {}", fs::canonicalize(&out_dir)?.display());
    Ok(())
}

/// The repo's web app, found from this crate's manifest so the command runs
/// from any directory.
fn default_out_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(DEFAULT_OUT_DIR)
}

/// Re-export every generated type and the version from one module.
fn index(out_dir: &Path) -> Result<String, Box<dyn Error>> {
    let mut names: Vec<String> = fs::read_dir(out_dir)?
        .filter_map(|entry| entry.ok())
        .filter_map(|entry| {
            let name = entry.file_name().to_string_lossy().into_owned();
            name.strip_suffix(".ts").map(str::to_owned)
        })
        .filter(|name| name != "index" && name != "version")
        .collect();
    names.sort();
    let mut index = NOTE.to_owned();
    for name in names {
        index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    index.push_str("export { PROTOCOL_VERSION } from \"./version\";\n");
    Ok(index)
}

/// Every sample message as the bytes the Rust encoder produces and the JSON
/// of the same value, for Vitest to decode and encode through the bridge.
#[derive(Serialize)]
struct Fixtures {
    client: Vec<Fixture>,
    server: Vec<Fixture>,
}

#[derive(Serialize)]
struct Fixture {
    name: &'static str,
    bytes: Vec<u8>,
    message: serde_json::Value,
}

fn fixtures() -> Result<String, Box<dyn Error>> {
    fn fixture<M: Serialize>((name, message): (&'static str, M)) -> Fixture {
        Fixture {
            name,
            bytes: encode(&message),
            message: serde_json::to_value(&message).expect("messages are JSON-encodable"),
        }
    }
    let fixtures = Fixtures {
        client: samples::client().into_iter().map(fixture).collect(),
        server: samples::server().into_iter().map(fixture).collect(),
    };
    let mut json = serde_json::to_string_pretty(&fixtures)?;
    json.push('\n');
    Ok(json)
}
